    protected void autonumber() {
        try {
            String sql = "SELECT id_nota FROM nota ORDER BY id_nota ASC";
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);
            
            txtidnota.setText("IN0001"); // Disamakan dengan txtidnota (sebelumnya tkode)
            
            while (rs.next()) {
                String id_nota = rs.getString("idnota").substring(2);
                int AN = Integer.parseInt(id_nota) + 1;
                String Nol = "";

                if (AN < 10) { Nol = "000"; } 
                else if (AN < 100) { Nol = "00"; } 
                else if (AN < 1000) { Nol = "0"; } 
                else if (AN < 10000) { Nol = ""; }

                txtidnota.setText("IN" + Nol + AN);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Auto Number Gagal: " + e.getMessage());
        }
    }
    
