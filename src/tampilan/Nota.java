    private void btambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btambahActionPerformed
        // TODO add your handling code here:
        try {
            String kode = txtkdbrg.getText();
            String namabrg = txtnmbrg.getText();
            int hargab = Integer.parseInt(txthb.getText());
            int hargaj = Integer.parseInt(txthj.getText());
            int qty = Integer.parseInt(txtqty.getText());
            int total = Integer.parseInt(txttotal.getText());

            tabmode.addRow(new Object[]{kode, namabrg, hargab, hargaj, qty, total});
            tbltransaksi.setModel(tabmode);
            
            // Mengosongkan form barang setelah masuk tabel
            txtkdbrg.setText("");
            txtnmbrg.setText("");
            txthb.setText("");
            txthj.setText("");
            txtqty.setText("");
            txttotal.setText("");
            
            hitung();
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Gagal menambah data. Pastikan semua field barang terisi angka yang benar!");
        } catch (Exception e) {
            System.out.println("Error : " + e);
        }
    }//GEN-LAST:event_btambahActionPerformed

    private void bhapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bhapusActionPerformed
        // TODO add your handling code here:
        int index = tbltransaksi.getSelectedRow();
        if (index != -1) { // Hanya hapus jika ada baris yang dipilih
            tabmode.removeRow(index);
            tbltransaksi.setModel(tabmode);
            hitung();
        } else {
            JOptionPane.showMessageDialog(null, "Pilih baris pada tabel terlebih dahulu yang ingin dihapus.");
        }
    }//GEN-LAST:event_bhapusActionPerformed

    private void bsimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bsimpanActionPerformed
        // TODO add your handling code here:
        SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
        String fd = sdf.format(jtgl.getValue());
        String sql = "INSERT INTO nota VALUES (?,?,?,?)";
        String zsql = "INSERT INTO isi VALUES (?,?,?,?,?)";
        
        try {
            // Menyimpan ke tabel Nota
            PreparedStatement stat = conn.prepareStatement(sql);
            stat.setString(1, txtidnota.getText());
            stat.setString(2, fd);
            stat.setString(3, txtid.getText()); // Asumsi txtid adalah ID Pelanggan
            stat.setString(4, jLabel16.getText()); // Asumsi ID Kasir
            stat.executeUpdate();

            // Menyimpan ke tabel Isi (Detail Transaksi)
            int t = tbltransaksi.getRowCount();
            PreparedStatement stat2 = conn.prepareStatement(zsql);
            
            for (int i = 0; i < t; i++) {
                String xkd = tbltransaksi.getValueAt(i, 0).toString();
                String xhb = tbltransaksi.getValueAt(i, 2).toString();
                String xhj = tbltransaksi.getValueAt(i, 3).toString();
                String xqty = tbltransaksi.getValueAt(i, 4).toString();

                stat2.setString(1, txtidnota.getText());
                stat2.setString(2, xkd);
                stat2.setString(3, xhb);
                stat2.setString(4, xhj);
                stat2.setString(5, xqty);
                stat2.executeUpdate();
            }
            
            JOptionPane.showMessageDialog(null, "Data berhasil disimpan");
            kosong();
            aktif();
            autonumber();
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Data gagal disimpan: " + e.getMessage());
        }
    }//GEN-LAST:event_bsimpanActionPerformed

