    protected void nama() {
        try {
            String sql = "SELECT * FROM kasir WHERE id_kasir = ?";
            PreparedStatement stat = conn.prepareStatement(sql);
            stat.setString(1, jLabel16.getText());
            ResultSet hasil = stat.executeQuery();

            if (hasil.next()) {
                jLabel17.setText(hasil.getString("nama_kasir"));
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Data kasir gagal dipanggil: " + e.getMessage());
        }
    }
    
